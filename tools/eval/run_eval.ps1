# Vision-layer baseline on SoccerNet-GSR: runs `eval` on the fixed sequence list
# (docs/eval-sequences.txt), combines the results and rewrites the generated block of
# docs/eval-baseline.md. Run after every change in the vision modules.
# Usage: tools/eval/run_eval.ps1 [-Dataset <path>] [-Split valid] [-Resume data/eval-runs/<run>]
#   -Resume continues an interrupted run (skips sequences that have a dump)
#   -Rescore data/eval-runs/<run> only re-scores that run's dumps (after a metric change), no pipeline
#   -FromCache data/eval-runs/<run> -Rerun StrongSortModule[,..] fast run: reuses that run's cached
#     pipeline state and reruns only the listed modules plus those consuming their outputs
#     (every full run saves its state under <run>/cache)
#   -Doc <file.md> writes the table there instead of docs/eval-baseline.md (experiments)
#   -Config <file.yaml> uses that pipeline config instead of configs/soccernet.yaml
#   -SeqsFile <file.txt> uses that sequence list instead of docs/eval-sequences.txt (e.g. the holdout set)
param(
    [string]$Dataset,
    [string]$Split = "valid",
    [string]$Resume,
    [string]$Rescore,
    [string]$FromCache,
    [string]$Rerun = "",
    [string]$Doc = "docs/eval-baseline.md",
    [string]$Config = "configs/soccernet.yaml",
    [string]$SeqsFile = "docs/eval-sequences.txt"
)
# native-command failures are checked via $LASTEXITCODE; "Stop" would turn dotnet stderr into terminating errors on PS 5.1
$ErrorActionPreference = "Continue"

$repo = (Resolve-Path (Join-Path $PSScriptRoot "../..")).Path
Set-Location $repo
if (-not $Dataset) { $Dataset = Join-Path $repo "data/SoccerNetGS" }
$config = $Config
$doc = if ([System.IO.Path]::IsPathRooted($Doc)) { $Doc } else { Join-Path $repo $Doc }
$seqs = Get-Content $SeqsFile | Where-Object { $_ -notmatch '^\s*#' -and $_.Trim() }
$run = if ($Rescore) { $Rescore } elseif ($Resume) { $Resume } else { "data/eval-runs/$(Get-Date -Format yyyyMMdd-HHmmss)" }
New-Item -ItemType Directory -Force $run | Out-Null

# Linux: ONNX Runtime CUDA needs the CUDA 12 / cuDNN 9 libs; take them from the pip venv
# (same one .vscode/launch.json uses) unless CUDA_LIBS points elsewhere
if ($IsLinux) {
    $cudaLibs = if ($env:CUDA_LIBS) { $env:CUDA_LIBS } else { Join-Path $HOME "cuda12-libs" }
    $libs = @(Get-ChildItem "$cudaLibs/lib/python3*/site-packages/nvidia/*/lib" -Directory -ErrorAction SilentlyContinue).FullName
    if ($libs.Count) { $env:LD_LIBRARY_PATH = (@($libs) + @($env:LD_LIBRARY_PATH | Where-Object { $_ })) -join ":" }
}

dotnet build src/PitchWise.Cli -c Release -v quiet -nologo
if ($LASTEXITCODE) { throw "build failed" }
foreach ($seq in $seqs) {
    if ($Rescore -or (Test-Path "$run/$seq.json")) { Write-Host "=== $seq (done, skipping) ==="; continue }
    Write-Host "=== $seq ==="
    $cacheArgs = if ($FromCache) { @("--from-cache", "$FromCache/cache", "--rerun", $Rerun) } else { @("--cache", "$run/cache") }
    dotnet run --project src/PitchWise.Cli -c Release --no-build -- `
        -c $config eval $Dataset $Split $seq --dump "$run/$seq.json" @cacheArgs 2>&1 | Tee-Object "$run/$seq.log"
    if ($LASTEXITCODE -or -not (Test-Path "$run/$seq.json")) { throw "eval failed for $seq (see $run/$seq.log)" }
}
$dumps = $seqs | ForEach-Object { "$run/$_.json" }
dotnet run --project src/PitchWise.Cli -c Release --no-build -- -c $config eval-combine "$run/combined.json" @dumps
if ($LASTEXITCODE) { throw "eval-combine failed" }

# --- metadata: what exactly was measured ---
$commit = git rev-parse --short HEAD
$dirty = @(git status --porcelain --untracked-files=no)
$providers = Select-String -Path "$run/*.log" `
    -Pattern 'ONNX [^ ]+: running on [A-Za-z]+( \(device [0-9]+\))?|ONNX CUDA provider unavailable for [^ :,]+' `
    -AllMatches | ForEach-Object { $_.Matches.Value } | Sort-Object -Unique
if (Select-String -Path "$run/*.log" -Pattern 'CUDA provider unavailable' -Quiet) {
    Write-Warning "some models fell back to CPU (see the provider list in $doc)"
}
$gpu = try { (nvidia-smi --query-gpu=name,driver_version --format=csv,noheader) -join "; " } catch { "n/a" }
$modelsDir = ((Select-String -Path $config -Pattern '^models_dir:\s*(\S+)').Matches.Groups[1].Value)

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("<!-- eval:begin (generated by tools/eval/run_eval.sh|.ps1 — do not edit by hand) -->")
$lines.Add("Pomiar: $(Get-Date -Format 'yyyy-MM-dd HH:mm'), split ``$Split``, $($seqs.Count) sekwencji (pełne, bez max_frames), wyniki w %.")
if ($FromCache) { $lines.Add("Bieg z cache ``$FromCache``: przeliczone tylko ``$Rerun`` i moduły zależne, reszta z cache.") }
$lines.Add("")
$lines.AddRange([string[]](Get-Content "$run/combined.md"))
$lines.Add("")
$lines.Add("- **Commit:** ``$commit``$(if ($dirty.Count) { ' + niezacommitowane zmiany:' } else { ' (czyste drzewo)' })")
foreach ($d in $dirty) { $lines.Add("  - ``$d``") }
$lines.Add("- **Provider ONNX (z logów):**")
foreach ($p in $providers) { $lines.Add("  - $p") }
$lines.Add("- **GPU:** $gpu")
$lines.Add("- **Surowe wyniki:** ``$run/``")
$lines.Add("- **Modele (sha256, pierwsze 12 znaków):**")
foreach ($pattern in "*.onnx", "*.onnx.data", "*.txt") {
    foreach ($f in Get-ChildItem (Join-Path $modelsDir $pattern) -File -ErrorAction SilentlyContinue | Sort-Object Name) {
        $hash = (Get-FileHash $f.FullName -Algorithm SHA256).Hash.ToLower().Substring(0, 12)
        $lines.Add("  - ``$($f.Name)`` $hash")
    }
}
$lines.Add("- **Config (``$config``):**")
$lines.Add("")
$lines.Add('```yaml')
$lines.AddRange([string[]](Get-Content $config))
$lines.Add('```')
$lines.Add("<!-- eval:end -->")
$block = $lines -join "`n"

New-Item -ItemType Directory -Force (Split-Path -Parent $doc) | Out-Null
$utf8 = [System.Text.UTF8Encoding]::new($false)
if ((Test-Path $doc) -and (Select-String -Path $doc -Pattern '<!-- eval:begin' -Quiet)) {
    $text = [System.IO.File]::ReadAllText($doc, $utf8)
    $text = [regex]::Replace($text, '(?s)<!-- eval:begin.*?<!-- eval:end -->', { param($m) $block })
    [System.IO.File]::WriteAllText($doc, $text, $utf8)
} else {
    [System.IO.File]::WriteAllText($doc, "# Baseline warstwy wizji — SoccerNet-GSR`n`n$block`n", $utf8)
}
Write-Host "Updated $doc"
