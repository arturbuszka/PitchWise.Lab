#!/usr/bin/env bash
# Vision-layer baseline on SoccerNet-GSR: runs `eval` on the fixed sequence list
# (docs/eval-sequences.txt), combines the results and rewrites the generated block of
# docs/eval-baseline.md. Run after every change in the vision modules.
# Usage: tools/eval/run_eval.sh [dataset_path] [split]
#   RESUME=data/eval-runs/<run> continues an interrupted run (skips sequences that have a dump)
#   RESCORE=data/eval-runs/<run> only re-scores that run's dumps (after a metric change), no pipeline
#   FROM_CACHE=data/eval-runs/<run> RERUN=StrongSortModule[,..] fast run: reuses that run's cached
#     pipeline state and reruns only the listed modules plus those consuming their outputs
#     (every full run saves its state under <run>/cache)
#   DOC=<file.md> writes the table there instead of docs/eval-baseline.md (experiments)
#   CONFIG=<file.yaml> uses that pipeline config instead of configs/soccernet.yaml
#   SEQS_FILE=<file.txt> uses that sequence list instead of docs/eval-sequences.txt (e.g. the holdout set)
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo"
dataset="${1:-$repo/data/SoccerNetGS}"
split="${2:-valid}"
config="${CONFIG:-configs/soccernet.yaml}"
doc="${DOC:-docs/eval-baseline.md}"
mapfile -t seqs < <(grep -v '^\s*#' "${SEQS_FILE:-docs/eval-sequences.txt}" | grep -v '^\s*$')
run="${RESCORE:-${RESUME:-data/eval-runs/$(date +%Y%m%d-%H%M%S)}}"
mkdir -p "$run"

# ONNX Runtime CUDA needs the CUDA 12 / cuDNN 9 libs; take them from the pip venv
# (same one .vscode/launch.json uses) unless CUDA_LIBS points elsewhere
cuda_libs="${CUDA_LIBS:-$HOME/cuda12-libs}"
if [ -d "$cuda_libs" ]; then
    libs="$(ls -d "$cuda_libs"/lib/python3*/site-packages/nvidia/*/lib 2>/dev/null | paste -sd: || true)"
    if [ -n "$libs" ]; then export LD_LIBRARY_PATH="$libs${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"; fi
fi

dotnet build src/PitchWise.Cli -c Release -v quiet -nologo
for seq in "${seqs[@]}"; do
    if [ -n "${RESCORE:-}" ] || [ -f "$run/$seq.json" ]; then echo "=== $seq (done, skipping) ==="; continue; fi
    echo "=== $seq ==="
    if [ -n "${FROM_CACHE:-}" ]; then
        cache_args=(--from-cache "$FROM_CACHE/cache" --rerun "${RERUN:-}")
    else
        cache_args=(--cache "$run/cache")
    fi
    dotnet run --project src/PitchWise.Cli -c Release --no-build -- \
        -c "$config" eval "$dataset" "$split" "$seq" --dump "$run/$seq.json" "${cache_args[@]}" 2>&1 | tee "$run/$seq.log"
    [ -f "$run/$seq.json" ] || { echo "eval failed for $seq (see $run/$seq.log)"; exit 1; }
done
dumps=()
for seq in "${seqs[@]}"; do dumps+=("$run/$seq.json"); done
dotnet run --project src/PitchWise.Cli -c Release --no-build -- -c "$config" eval-combine "$run/combined.json" "${dumps[@]}"

# --- metadata: what exactly was measured ---
commit="$(git rev-parse --short HEAD)"
dirty="$(git status --porcelain --untracked-files=no)"
providers="$(grep -ohE 'ONNX [^ ]+: running on [A-Za-z]+( \(device [0-9]+\))?|ONNX CUDA provider unavailable for [^ :,]+' "$run"/*.log | sort -u || true)"
if grep -q 'CUDA provider unavailable' "$run"/*.log; then
    echo "WARNING: some models fell back to CPU (see the provider list in $doc)" >&2
fi
gpu="$(nvidia-smi --query-gpu=name,driver_version --format=csv,noheader 2>/dev/null || echo n/a)"
models_dir="$(grep -E '^models_dir:' "$config" | awk '{print $2}')"

block="$run/block.md"
{
    echo "<!-- eval:begin (generated by tools/eval/run_eval.sh|.ps1 — do not edit by hand) -->"
    echo "Pomiar: $(date '+%Y-%m-%d %H:%M'), split \`$split\`, ${#seqs[@]} sekwencji (pełne, bez max_frames), wyniki w %."
    if [ -n "${FROM_CACHE:-}" ]; then
        echo "Bieg z cache \`$FROM_CACHE\`: przeliczone tylko \`${RERUN:-}\` i moduły zależne, reszta z cache."
    fi
    echo
    cat "$run/combined.md"
    echo
    echo "- **Commit:** \`$commit\`$([ -n "$dirty" ] && echo ' + niezacommitowane zmiany:' || echo ' (czyste drzewo)')"
    if [ -n "$dirty" ]; then echo "$dirty" | sed 's/^/  - `/; s/$/`/'; fi
    echo "- **Provider ONNX (z logów):**"
    echo "$providers" | sed 's/^/  - /'
    echo "- **GPU:** $gpu"
    echo "- **Surowe wyniki:** \`$run/\`"
    echo "- **Modele (sha256, pierwsze 12 znaków):**"
    for f in "$models_dir"/*.onnx "$models_dir"/*.onnx.data "$models_dir"/*.txt; do
        if [ -f "$f" ]; then echo "  - \`$(basename "$f")\` $(sha256sum "$f" | cut -c1-12)"; fi
    done
    echo "- **Config (\`$config\`):**"
    echo
    echo '```yaml'
    cat "$config"
    echo '```'
    echo "<!-- eval:end -->"
} > "$block"

mkdir -p "$(dirname "$doc")"
if [ -f "$doc" ] && grep -q '<!-- eval:begin' "$doc"; then
    awk -v blk="$block" '
        /<!-- eval:begin/ { while ((getline l < blk) > 0) print l; skip = 1; next }
        /<!-- eval:end -->/ { skip = 0; next }
        !skip { print }' "$doc" > "$run/doc.md"
    mv "$run/doc.md" "$doc"
else
    { echo "# Baseline warstwy wizji — SoccerNet-GSR"; echo; cat "$block"; } > "$doc"
fi
echo "Updated $doc"
